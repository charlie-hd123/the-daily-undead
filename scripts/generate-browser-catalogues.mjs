import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = fileURLToPath(new URL("../", import.meta.url));

export async function browserCatalogues(root = projectRoot) {
  const read = async (name) => JSON.parse(await readFile(path.join(root, name), "utf8"));
  const catalog = await read("data/maps/index.json");
  const maps = await Promise.all(catalog.maps.map((name) => read(`data/maps/${name}`)));
  const words = await read("data/word-puzzle-demo.json");
  const assets = new Map();
  const urls = {};
  for (const [name, value] of Object.entries({ maps: { catalog, maps }, words })) {
    const content = `${JSON.stringify(value)}\n`;
    const hash = createHash("sha256").update(content).digest("hex");
    const filename = `data/catalogues/${name}.${hash}.json`;
    assets.set(filename, content);
    urls[name] = `./${filename}`;
  }
  assets.set("js/puzzle-catalogue-assets.js", `// Generated by scripts/generate-browser-catalogues.mjs. Do not edit.\nexport const puzzleCatalogueUrls = ${JSON.stringify(urls, null, 2)};\n`);
  return assets;
}

export async function generateBrowserCatalogues(root = projectRoot) {
  const assets = await browserCatalogues(root);
  for (const [name, content] of assets) {
    await mkdir(path.dirname(path.join(root, name)), { recursive: true });
    await writeFile(path.join(root, name), content);
  }
  // Keep previously released hashes: an older open page may still need them.
  return assets;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const assets = await generateBrowserCatalogues();
  console.log(`Generated ${assets.size - 1} content-addressed browser catalogues. Add new catalogue files deliberately before preview/release.`);
}
