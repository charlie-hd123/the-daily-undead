import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { buildDailyBloodTiesPuzzle } from '../js/blood-ties-core.js';

export const catalogueFrom = '2026-10-22';
export const catalogueThrough = '2029-12-31';
// Include every input to the generator, including historical content and rules.
const sourceNames = [
  'game-core.js', 'blood-ties-core.js', 'blood-ties-content.js',
  'blood-ties-v2.js', 'blood-ties-legacy.js', 'blood-ties-discovery.js',
  'blood-ties-catalogue.js', 'blood-ties-catalogue-v1.js', 'blood-ties-catalogue-v2.js',
  'blood-ties-catalogue-v3.js', 'blood-ties-catalogue-v4.js',
  'blood-ties-boards.js',
  'blood-ties-boards-v2.js', 'blood-ties-boards-v3.js',
  'blood-ties-boards-v4.js',
];

export async function bloodTiesSourceDigest() {
  const hash = createHash('sha256');
  for (const name of sourceNames) {
    hash.update(name);
    hash.update(await readFile(new URL(`../js/${name}`, import.meta.url)));
  }
  return hash.digest('hex');
}

export async function generateWorkerBloodTiesCatalogue() {
  const groups = [], groupIds = new Map();
  const schedules = {};
  for (const production of [false, true]) {
    const days = [];
    for (let time = Date.parse(`${catalogueFrom}T00:00:00Z`); time <= Date.parse(`${catalogueThrough}T00:00:00Z`); time += 86400000) {
      const dateKey = new Date(time).toISOString().slice(0, 10);
      const puzzle = buildDailyBloodTiesPuzzle(dateKey, { production });
      const ids = puzzle.groups.map(group => {
        const json = JSON.stringify(group);
        if (!groupIds.has(json)) { groupIds.set(json, groups.length); groups.push(group); }
        return groupIds.get(json);
      });
      days.push([puzzle.key, puzzle.contentVersion, ids, puzzle.tiles, puzzle.redHerrings]);
    }
    schedules[production ? 'production' : 'staging'] = days;
  }
  return { from: catalogueFrom, through: catalogueThrough, sourceDigest: await bloodTiesSourceDigest(), groups, schedules };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalogue = await generateWorkerBloodTiesCatalogue();
  await writeFile(new URL('../worker/src/generated-blood-ties-catalog.js', import.meta.url),
    `// Generated by scripts/generate-worker-blood-ties.mjs. Do not edit.\nexport const workerBloodTiesCatalogue = ${JSON.stringify(catalogue)};\n`);
  console.log(`Compiled both unchanged Blood Ties schedules: ${catalogue.from} through ${catalogue.through}.`);
}
