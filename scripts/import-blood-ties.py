"""Import ONLY the first worksheet; no hand-authored connections or extra sheets.

Usage: python3 scripts/import-blood-ties.py path/to/workbook.xlsx
Uses the XLSX XML directly so catalogue updates need no Python dependencies.
"""
import hashlib
import json
import pathlib
import sys
import zipfile
import xml.etree.ElementTree as ET

source = pathlib.Path(sys.argv[1])
ns = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
with zipfile.ZipFile(source) as book:
    strings = []
    if "xl/sharedStrings.xml" in book.namelist():
        strings = ["".join(si.itertext()) for si in ET.fromstring(book.read("xl/sharedStrings.xml"))]
    first = ET.fromstring(book.read("xl/workbook.xml")).find("s:sheets/s:sheet", ns)
    rel_id = first.attrib["{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"]
    relationships = ET.fromstring(book.read("xl/_rels/workbook.xml.rels"))
    target = next(r.attrib["Target"] for r in relationships if r.attrib["Id"] == rel_id)
    target = target.lstrip("/") if target.startswith("/") else "xl/" + target
    rows = []
    for row in ET.fromstring(book.read(target)).findall("s:sheetData/s:row", ns):
        cells = {}
        for cell in row:
            column = "".join(c for c in cell.attrib["r"] if c.isalpha())
            value = cell.findtext("s:v", default="", namespaces=ns)
            if cell.attrib.get("t") == "s":
                value = strings[int(value)]
            elif cell.attrib.get("t") == "inlineStr":
                value = "".join(cell.find("s:is", ns).itertext())
            cells[column] = value.strip()
        rows.append(cells)
    assert rows[0].get("A") == "Connection ID" and rows[0].get("F") == "Eligible tile 01"
    connections = []
    ids = set()
    for row in rows[1:]:
        if not row.get("A"):
            continue
        tiles = list(dict.fromkeys(row.get(chr(70 + i), "").strip() for i in range(16)))
        tiles = [tile for tile in tiles if tile]
        if len(tiles) < 3:
            continue
        assert row["A"] not in ids and all(row.get(key) for key in ["B", "C", "D", "E"])
        ids.add(row["A"])
        connections.append(dict(id=row["A"], name=row["B"], definition=row["C"], family=row["D"], difficulty=int(row["E"]), tiles=tiles, researchLink=row.get("V", "")))

catalogue = dict(version=1, source=source.name, sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(), worksheet=first.attrib["name"], connections=connections)
output = pathlib.Path(__file__).resolve().parents[1] / "js/blood-ties-catalogue.js"
output.write_text("// Generated by scripts/import-blood-ties.py from the first worksheet only.\nexport const bloodTiesCatalogue = " + json.dumps(catalogue, ensure_ascii=False, indent=2) + ";\n")
print(f"Imported {len(connections)} connections from first worksheet: {first.attrib['name']}")
