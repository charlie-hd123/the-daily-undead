import fs from "node:fs/promises";

const projectRoot = new URL("../", import.meta.url);
const index = JSON.parse(await fs.readFile(new URL("data/maps/index.json", projectRoot), "utf8"));
const maps = await Promise.all(
  index.maps.map(async (filename) => {
    const map = JSON.parse(
      await fs.readFile(new URL(`data/maps/${filename}`, projectRoot), "utf8"),
    );
    return {
      id: map.id,
      title: map.title,
      availableFrom: map.availableFrom,
      steps: map.steps.map(({ id, order }) => ({ id, order })),
    };
  }),
);

const profileGames = index.games.map(({ title }) => title);
const profileMaps = [
  ...maps.map(({ title }) => title),
  ...(index.selectionOnlyMaps || []).map(({ title }) => title),
];

const source = `// Generated by scripts/generate-worker-catalog.js. Do not edit by hand.\nexport const workerMaps = ${JSON.stringify(maps, null, 2)};\n\nexport const answerEquivalents = ${JSON.stringify(index.answerEquivalents || [], null, 2)};\n\nexport const profileGames = ${JSON.stringify(profileGames, null, 2)};\n\nexport const profileMaps = ${JSON.stringify(profileMaps, null, 2)};\n`;

await fs.writeFile(new URL("worker/src/generated-map-catalog.js", projectRoot), source);
