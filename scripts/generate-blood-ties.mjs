// Compile a verified pool once, rather than search thousands of boards in a Worker request.
import { readFile, writeFile } from 'node:fs/promises';
import { bloodTiesCatalogue as catalogue } from '../js/blood-ties-catalogue.js';
import { countBloodTiesSolutions } from '../js/blood-ties-legacy.js';
import { createRng, hashString, shuffle } from '../js/game-core.js';

const random = createRng(hashString(`blood-ties:v2:${catalogue.sourceSha256}`));
const byDifficulty = [1, 2, 3].map(d => catalogue.connections.filter(g => g.difficulty === d));
const pool = [], seen = new Set(), coverage = new Map();
for (let attempt = 0; attempt < 1000000 && pool.length < 4096; attempt++) {
  const pick = list => list[Math.floor(random() * list.length)];
  const selected = [pick(byDifficulty[0]), ...shuffle(byDifficulty[1], random).slice(0, 2), pick(byDifficulty[2])];
  const families = selected.map(g => g.family);
  if (families.some(f => families.filter(other => other === f).length > 2)) continue;
  const used = new Set();
  const groups = shuffle(selected, random).map(g => {
    const answers = shuffle(g.tiles.filter(t => !used.has(t)), random).slice(0, 3);
    answers.forEach(t => used.add(t));
    return { ...g, answers };
  });
  if (groups.some(g => g.answers.length !== 3)) continue;
  const tiles = groups.flatMap(g => g.answers);
  const traps = groups.flatMap(owner => owner.answers.filter(t => groups.some(g => g.id !== owner.id && g.tiles.includes(t))));
  if (traps.length < 2 || countBloodTiesSolutions(groups, tiles) !== 1) continue;
  const signature = groups.map(g => `${g.id}:${[...g.answers].sort().join('\u001f')}`).sort().join('|');
  if (seen.has(signature)) continue;
  seen.add(signature);
  // Compact indices refer only to this exact workbook digest.
  pool.push(groups.map(g => [g.id, ...g.answers.map(t => g.tiles.indexOf(t))]));
  groups.forEach(g => coverage.set(g.id, (coverage.get(g.id) || 0) + 1));
}
if (pool.length !== 4096 || coverage.size !== catalogue.connections.length) {
  throw new Error(`Insufficient board coverage: ${pool.length} boards, ${coverage.size}/${catalogue.connections.length} categories`);
}
const data = { version: 2, sourceSha256: catalogue.sourceSha256, boards: pool };
const content = '// Generated by scripts/generate-blood-ties.mjs. Do not edit.\nexport const bloodTiesBoards = ' + JSON.stringify(data) + ';\n';
const output = new URL('../js/blood-ties-boards.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('Blood Ties pool is stale. Run node scripts/generate-blood-ties.mjs.');
} else await writeFile(output, content);
console.log(`Blood Ties: ${pool.length} unique-solution boards, all ${coverage.size} categories covered.`);
