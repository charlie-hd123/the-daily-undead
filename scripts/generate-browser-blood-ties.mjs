import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bloodTiesCatalogueQuarter } from '../js/blood-ties-compiled.js';
import { workerBloodTiesCatalogue } from '../worker/src/generated-blood-ties-catalog.js';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));

export function browserBloodTiesAssets(catalogue = workerBloodTiesCatalogue) {
  const assets = new Map();
  const urls = {};
  const start = Date.parse(catalogue.from);
  for (const [environment, schedule] of Object.entries(catalogue.schedules)) {
    const chunks = new Map();
    urls[environment] = {};
    for (const [index, [key, version, ids, tiles, redHerrings]] of schedule.entries()) {
      const dateKey = new Date(start + index * 86400000).toISOString().slice(0, 10);
      const quarter = bloodTiesCatalogueQuarter(dateKey);
      if (!chunks.has(quarter)) {
        chunks.set(quarter, { environment, from: dateKey, through: dateKey, groups: [], days: [], indices: new Map() });
      }
      const chunk = chunks.get(quarter);
      chunk.through = dateKey;
      const localIds = ids.map(id => {
        if (!chunk.indices.has(id)) {
          chunk.indices.set(id, chunk.groups.length);
          chunk.groups.push(catalogue.groups[id]);
        }
        return chunk.indices.get(id);
      });
      chunk.days.push([key, version, localIds, tiles, redHerrings]);
    }
    for (const [quarter, { indices, ...chunk }] of chunks) {
      const content = `${JSON.stringify(chunk)}\n`;
      const hash = createHash('sha256').update(content).digest('hex');
      const name = `data/catalogues/blood-${environment}-${quarter}.${hash}.json`;
      assets.set(name, content);
      urls[environment][quarter] = `./${name}`;
    }
  }
  assets.set('js/blood-ties-catalogue-assets.js',
    `// Generated by scripts/generate-browser-blood-ties.mjs. Do not edit.\nexport const bloodTiesCatalogueUrls = ${JSON.stringify(urls, null, 2)};\n`);
  return assets;
}

export async function generateBrowserBloodTiesAssets(root = projectRoot) {
  for (const [name, content] of browserBloodTiesAssets()) {
    const file = path.join(root, name);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, content);
  }
  // Older releases can keep using the immutable catalogue URLs they know.
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateBrowserBloodTiesAssets();
}
